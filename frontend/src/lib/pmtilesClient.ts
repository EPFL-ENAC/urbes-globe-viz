import maplibregl from "maplibre-gl";
import { Protocol, PMTiles } from "pmtiles";
import type { RequestParameters, GetResourceResponse } from "maplibre-gl";

// Singleton protocol shared across every component that mounts a maplibregl.Map.
// Keeping a single instance means the directory cache (header + root + leaf
// directories) is reused — switching from the globe to a project map doesn't
// re-fetch the same metadata.
export const pmtilesProtocol = new Protocol();

/**
 * Protocol handler to register with `maplibregl.addProtocol("pmtiles", …)`.
 *
 * The GHSL archive omits near-empty tiles (ocean — the build pipeline deletes
 * tiles < 500 B), for which `Protocol.tile` resolves `{data: null}`. MapLibre's
 * image request path settles neither success nor error on a null payload, so
 * those raster tiles would sit in state "loading" forever — blocking `idle` /
 * `areTilesLoaded()` whenever ocean is in view and disqualifying them as
 * zoom fallbacks. Substitute an empty buffer, which MapLibre turns into a
 * transparent loaded tile (the basemap's background shows through, matching
 * GHSL ocean). TileJSON requests pass through untouched.
 */
export async function pmtilesRequest(
  params: RequestParameters,
  abortController: AbortController,
): Promise<GetResourceResponse<unknown>> {
  const response = await pmtilesProtocol.tile(params, abortController);
  if (params.type !== "json" && response.data == null) {
    return { ...response, data: new Uint8Array() };
  }
  return response;
}

const GHSL_LIVE_URL = "https://urbes-viz.epfl.ch/geodata/ghsl.pmtiles";

// Zoom levels served from the bundled local pyramid in public/ghsl-low/
// (generated by scripts/extract-ghsl-low.mjs) instead of the remote archive.
const GHSL_LOW_MAX_ZOOM = 5;

// The one PMTiles instance of the remote archive. The protocol finds it by its
// URL, so MapLibre requests and our prefetch share the same header and
// directory cache.
const ghslArchive = new PMTiles(GHSL_LIVE_URL);
pmtilesProtocol.add(ghslArchive);

// MapLibre runs every image request of the page in one queue: 16 at once by
// default, 8 while any map moves (that one can't be changed). Measured on a
// still project map (Nov 2026): 32 starts all the GHSL requests of the view at
// once, but the time to `idle` hardly moves, because the server answers range
// requests about one every 10 ms even in parallel. Going higher gives nothing.
const MAX_PARALLEL_IMAGE_REQUESTS = 32;

// --- Prefetch cache ---
//
// Before a flyTo, the app asks for the tiles of the destination view (see
// prefetchView in useGhslBasemap.ts). We load them here, outside the MapLibre
// queue, so they are on the way during the whole flight. ghslRequest reads
// this cache first, so when MapLibre asks for the same tile it gets the bytes
// at once, or waits for the request already running.

// GHSL tiles are about 10 KB (40 KB at most), so 5 to 20 MB. MapLibre keeps
// its own tile cache, this one only has to hold the last few flights.
const TILE_CACHE_SIZE = 512;

interface CachedTile {
  key: string;
  bytes: Promise<ArrayBuffer>;
  controller: AbortController;
  done: boolean;
  // How many prefetches still want this tile while it loads. The load is
  // cancelled only when this drops to 0, so a new flight keeps the tiles it
  // shares with the flight it interrupts.
  users: number;
}

// Insertion order = use order (we delete and set again on each hit), so the
// first key is the least recently used one.
const tileCache = new Map<string, CachedTile>();

export interface TileCoord {
  z: number;
  x: number;
  y: number;
}

const tileKey = (z: number | string, x: number | string, y: number | string) =>
  `${z}/${x}/${y}`;

// Loads the bytes of one tile, from the same backend ghslRequest uses. An ocean
// tile left out of the archive becomes an empty buffer (a transparent tile),
// the same rule as the null-data fix in pmtilesRequest.
async function loadTileBytes(
  { z, x, y }: TileCoord,
  signal: AbortSignal,
): Promise<ArrayBuffer> {
  if (z <= GHSL_LOW_MAX_ZOOM) {
    const response = await fetch(`/ghsl-low/${z}/${x}/${y}.webp`, { signal });
    if (!response.ok) return new ArrayBuffer(0);
    return response.arrayBuffer();
  }
  const response = await ghslArchive.getZxy(z, x, y, signal);
  return response?.data ?? new ArrayBuffer(0);
}

function cacheTile(coord: TileCoord): CachedTile {
  const key = tileKey(coord.z, coord.x, coord.y);
  const controller = new AbortController();
  const entry: CachedTile = {
    key,
    controller,
    done: false,
    users: 0,
    bytes: loadTileBytes(coord, controller.signal),
  };
  entry.bytes.then(
    () => {
      entry.done = true;
    },
    () => {
      // Failed or cancelled: forget it, so the next request loads it again.
      entry.done = true;
      if (tileCache.get(key) === entry) tileCache.delete(key);
    },
  );
  tileCache.set(key, entry);
  while (tileCache.size > TILE_CACHE_SIZE) {
    const [oldestKey, oldest] = tileCache.entries().next().value!;
    tileCache.delete(oldestKey);
    if (!oldest.done) oldest.controller.abort();
  }
  return entry;
}

/**
 * Starts loading `tiles` (in this order) into the prefetch cache. Tiles that
 * are already there are not loaded again. Returns a function that cancels the
 * loads of this call that are still running and that no other prefetch wants.
 */
export function prefetchGhslTiles(tiles: TileCoord[]): () => void {
  const claimed: CachedTile[] = [];
  for (const tile of tiles) {
    const entry =
      tileCache.get(tileKey(tile.z, tile.x, tile.y)) ?? cacheTile(tile);
    if (entry.done) continue;
    entry.users++;
    claimed.push(entry);
  }
  let cancelled = false;
  return () => {
    if (cancelled) return;
    cancelled = true;
    for (const entry of claimed) {
      entry.users--;
      if (entry.users > 0 || entry.done) continue;
      entry.controller.abort();
      // Forget it now, not when the promise rejects, so a prefetch that
      // starts right after this one loads it again.
      if (tileCache.get(entry.key) === entry) tileCache.delete(entry.key);
    }
  };
}

// The cached bytes of a tile, or null when it is not in the cache or its load
// failed or was cancelled.
async function readCachedTile(key: string): Promise<ArrayBuffer | null> {
  const entry = tileCache.get(key);
  if (!entry) return null;
  tileCache.delete(key);
  tileCache.set(key, entry);
  try {
    // A copy: the cache keeps its own bytes in case MapLibre ever transfers
    // the buffer it gets.
    return (await entry.bytes).slice(0);
  } catch {
    return null;
  }
}

/**
 * Handler for the "ghsl://{z}/{x}/{y}" protocol behind the ghsl-urban raster
 * source. One source, two backends: z0–5 come from the bundled local tiles
 * (same-origin, browser-cached — they paint within a few frames on first load
 * and are near-instant fallbacks when MapLibre requests coarse ancestors of a
 * still-loading deep tile), z6+ from the remote PMTiles archive. Keeping it a
 * single source means MapLibre swaps a coarse tile for the sharp one when it
 * arrives, instead of blending two raster layers — GHSL tiles have transparent
 * no-settlement pixels, so a stacked low-res layer would stay visible through
 * loaded high-res tiles forever.
 *
 * A tile prefetched for a flight comes from the prefetch cache first.
 */
export async function ghslRequest(
  params: RequestParameters,
  abortController: AbortController,
): Promise<GetResourceResponse<unknown>> {
  const match = params.url.match(/^ghsl:\/\/(\d+)\/(\d+)\/(\d+)$/);
  if (!match) throw new Error(`Unexpected ghsl tile URL: ${params.url}`);
  const [, z, x, y] = match;

  const cached = await readCachedTile(tileKey(z!, x!, y!));
  if (cached) return { data: cached };

  if (Number(z) <= GHSL_LOW_MAX_ZOOM) {
    const response = await fetch(`/ghsl-low/${z}/${x}/${y}.webp`, {
      signal: abortController.signal,
    });
    // The local pyramid is complete (missing-ocean tiles ship as transparent
    // placeholders), so a miss here is exceptional — degrade to an empty
    // (transparent) tile rather than an errored one.
    if (!response.ok) return { data: new Uint8Array() };
    return { data: await response.arrayBuffer() };
  }

  return pmtilesRequest(
    { ...params, url: `pmtiles://${GHSL_LIVE_URL}/${z}/${x}/${y}` },
    abortController,
  );
}

let protocolsRegistered = false;

// Registers the shared "pmtiles" and "ghsl" protocols once, app-wide. Every
// component that mounts a maplibregl.Map calls this before constructing it.
export function registerProtocols(): void {
  if (protocolsRegistered) return;
  protocolsRegistered = true;
  maplibregl.addProtocol("pmtiles", pmtilesRequest);
  maplibregl.addProtocol("ghsl", ghslRequest);
  maplibregl.setMaxParallelImageRequests(MAX_PARALLEL_IMAGE_REQUESTS);
}

// Kicks off the PMTiles header + root-directory range request before any map
// canvas mounts. Called from main.ts, so the fetch runs in parallel with
// Vue/Pinia/router/Quasar setup. By the time Globe3D mounts, the directory
// cache is warm and tile reads start immediately.
export function prefetchGhsl(): void {
  void ghslArchive.getHeader();
}
